/**
 * Automated second-source cross-check (DECISIONS D-018).
 *
 * Usage: tsx scripts/cross-check.ts <dir-with-season-texts>
 * The directory holds plain-text extracts of per-season Netflix Tudum articles, named
 * season-<n>.txt with the article URL on the first line. Source text is never committed
 * (copyright); only the corroboration result is written to content/the-diplomat/corroboration.ts.
 *
 * A fact counts as corroborated by a season article when every mentioned character's surname
 * appears in it and at least 60% of the fact's distinctive words (by 5-letter stem) do too.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import show from "../content/the-diplomat/base";

const dir = process.argv[2];
if (!dir) throw new Error("usage: cross-check.ts <dir>");
const STOP = new Set("about after again against also another back because been before being between both could does down during each even ever from have here into just like made make many more most much must never only other over same should since some such than that their them then there these they this those through under until very want were what when where which while will with would your says said tells told".split(" "));
const stems = (t: string) => new Set(t.toLowerCase().match(/[a-z]{4,}/g)?.filter((w) => !STOP.has(w)).map((w) => w.slice(0, 5)) ?? []);
const today = new Date().toISOString().slice(0, 10);

const seasons = new Map<number, { url: string; text: string; words: Set<string> }>();
for (const n of [1, 2, 3, 4]) {
  const f = join(dir, `season-${n}.txt`);
  if (!existsSync(f)) continue;
  const [url, ...rest] = readFileSync(f, "utf8").split("\n");
  const text = rest.join("\n");
  seasons.set(n, { url: url!.trim(), text: text.toLowerCase(), words: stems(text) });
}
const surname = new Map(show.characters.map((c) => [c.id, c.name.split(" ").at(-1)!.toLowerCase()]));

const out: Record<string, string> = {};
let total = 0, ok = 0;
for (const ch of show.characters) for (const f of ch.facts) {
  total++;
  const s = seasons.get(f.revealAt.season);
  if (!s) continue;
  const names = [...new Set([ch.id, ...f.mentions])].map((m) => surname.get(m)!);
  if (!names.every((n) => s.text.includes(n))) continue;
  const w = [...stems(f.text)];
  const hit = w.filter((x) => s.words.has(x)).length;
  if (w.length && hit / w.length >= 0.6) { out[f.text] = s.url; ok++; }
}
const body = `// Generated by scripts/cross-check.ts on ${today}. Do not edit by hand.
// Maps fact text -> second-source URL that corroborates it (automated keyword cross-check).
export const corroboration: Record<string, string> = ${JSON.stringify(out, null, 2)};
export const checkedOn = "${today}";
`;
writeFileSync(join(import.meta.dirname, "../content/the-diplomat/corroboration.ts"), body);
console.log(`corroborated ${ok}/${total} facts`);
